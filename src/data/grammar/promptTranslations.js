/**
 * Intelligent helper to get the English translation for any grammar question prompt.
 * If the prompt is already in English (e.g. Translate: '...'), it returns null.
 * Otherwise it extracts or translates the German sentence into natural English.
 */
export function getGrammarPromptTranslation(q) {
  if (!q) return null;

  // 1. Explicit property on question
  if (q.promptEn) return q.promptEn;

  // 2. Direct lookup in curated dictionary
  if (q.id && PROMPT_TRANSLATIONS[q.id]) {
    return PROMPT_TRANSLATIONS[q.id];
  }

  const prompt = (q.prompt || '').trim();

  // 3. If prompt is already an English translation instruction
  if (prompt.startsWith("Translate:") || prompt.startsWith("Translate :")) {
    return null; // Already English
  }

  // 4. Spot the mistake pattern
  if (prompt.startsWith("Finde den Fehler:")) {
    const quoteMatch = prompt.match(/['"]([^'"]+)['"]/);
    if (quoteMatch) {
      return `Spot the error in the German sentence: "${quoteMatch[1]}"`;
    }
    return "Spot and fix the grammatical error in this sentence.";
  }

  // 5. Word order pattern
  if (prompt.includes("Welche Wortstellung") || prompt.includes("richtige Reihenfolge")) {
    return "Which word order is grammatically correct?";
  }

  if (prompt.includes("Welcher Satz") || prompt.includes("Welcher Ausdruck")) {
    return "Which sentence or phrasing is grammatically correct?";
  }

  if (prompt.includes("Welcher Artikel")) {
    return "Which grammatical article (der / die / das) belongs here?";
  }

  // 6. If question has an English explanation that mentions the meaning
  if (q.explanationEn) {
    const meaningMatch = q.explanationEn.match(/["']([^"']+)["']\s*(?:means|=|corresponds to|translation)/i) ||
                         q.explanationEn.match(/(?:means|=|corresponds to)\s*["']([^"']+)["']/i);
    if (meaningMatch) {
      return meaningMatch[1];
    }
  }

  // 7. General fallback: if question prompt contains German characters (ä, ö, ü, ß) or typical German words
  const isGerman = /[äöüß]/i.test(prompt) ||
    /\b(der|die|das|den|dem|des|ein|eine|einer|eines|und|oder|aber|weil|dass|obwohl|wenn|nachdem|als|nicht|mit|für|in|an|auf|aus|bei|nach|zu|vom|im|am|vor|über|unter|zwischen|während|trotz|wegen)\b/i.test(prompt);

  if (isGerman) {
    // Generate a readable clean prompt gloss if gap exists
    if (prompt.includes("___")) {
      return "Fill in the blank with the grammatically correct form.";
    }
    return "Select the correct grammatical answer.";
  }

  return null;
}
